const {contextBridge, ipcRenderer} = require('electron');
contextBridge.exposeInMainWorld('fabBrowser', {
  stop:()=>ipcRenderer.invoke('stop'),
  zoom:direction=>ipcRenderer.invoke('zoom',direction),
  find:(text,options)=>ipcRenderer.invoke('find',text,options),
  stopFind:()=>ipcRenderer.invoke('stopFind'),
  findOpen:open=>ipcRenderer.invoke('findOpen',open),
  onFindResult:callback=>ipcRenderer.on('findResult',(_event,value)=>callback(value)),
  onCloseFind:callback=>ipcRenderer.on('closeFind',()=>callback()),
  onShowFind:callback=>ipcRenderer.on('showFind',(_event,value)=>callback(value)),
  onShowLibrary:callback=>ipcRenderer.on('showLibrary',()=>callback()),
  onLibraryChanged:callback=>ipcRenderer.on('libraryChanged',()=>callback()),
  sidebar: open => ipcRenderer.invoke('sidebar', Boolean(open)),
  newTab: () => ipcRenderer.invoke('newTab'),
  closeTab: id => ipcRenderer.invoke('closeTab', id),
  activateTab: id => ipcRenderer.invoke('activateTab', id),
  onTabs: callback => {const fn=(_event,data)=>callback(data);ipcRenderer.on('tabs',fn);return()=>ipcRenderer.removeListener('tabs',fn);},
  onFocusAddress: callback => {const fn=()=>callback();ipcRenderer.on('focusAddress',fn);return()=>ipcRenderer.removeListener('focusAddress',fn);},
  initial: () => ipcRenderer.invoke('initial'),
  library: () => ipcRenderer.invoke('library'), bookmark: () => ipcRenderer.invoke('bookmark'),
  removeHistory:value=>ipcRenderer.invoke('removeHistory',value),removeBookmark:value=>ipcRenderer.invoke('removeBookmark',value),clearHistory:()=>ipcRenderer.invoke('clearHistory'),
  navigate: value => ipcRenderer.invoke('navigate', String(value)),
  back: () => ipcRenderer.invoke('back'), forward: () => ipcRenderer.invoke('forward'),
  reload: () => ipcRenderer.invoke('reload'), developer: () => ipcRenderer.invoke('developer'),
  onState: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('state', listener); return () => ipcRenderer.removeListener('state', listener); },
});
